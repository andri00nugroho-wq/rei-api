$findArticle = $pdo->prepare('SELECT id FROM posts WHERE slug = :slug LIMIT 1');
$insertArticle = $pdo->prepare(
    'INSERT INTO posts (title, slug, content, featured_image, type)
     VALUES (:title, :slug, :content, :featured_image, :type)'
);

$pdo->beginTransaction();

try {
    foreach ($articles as $article) {
        $findArticle->execute(['slug' => $article['slug']]);

        if ($findArticle->fetchColumn() !== false) {
            echo "Skipped existing article: {$article['slug']}\n";
            continue;
        }

        $paragraphs = array_map(
            static fn (string $paragraph): string => '<p>' . htmlspecialchars($paragraph, ENT_QUOTES, 'UTF-8') . '</p>',
            $article['content']
        );
        $insertArticle->execute([
            'title' => $article['title'],
            'slug' => $article['slug'],
            'content' => implode("\n", $paragraphs),
            'featured_image' => $article['featured_image'],
            'type' => 'post',
        ]);

        echo "Added article: {$article['slug']}\n";
    }

    $pdo->commit();
} catch (Throwable $error) {
    if ($pdo->inTransaction()) {
        $pdo->rollBack();
    }

    throw $error;
}
